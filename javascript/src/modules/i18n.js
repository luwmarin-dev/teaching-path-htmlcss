export function t(key, lang = 'en') {
  const currentLang = (lang === 'uz') ? 'uz' : 'en';
  return UI_TEXT[currentLang]?.[key] || UI_TEXT.en[key] || key;
}

export function escapeHtml(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
